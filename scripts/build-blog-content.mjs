// Runs before `vite build`. Parses content/blog/*.md and writes a generated
// TS module the client app imports directly, so /blog and /blog/:slug work
// as normal fast in-app navigation with zero markdown parsing shipped to
// the browser bundle (gray-matter/marked stay build-time-only deps).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadBlogPosts } from './lib/blogContent.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const contentDir = path.join(__dirname, '..', 'content', 'blog');
const outFile = path.join(__dirname, '..', 'src', 'content', 'blogPosts.generated.ts');

const posts = loadBlogPosts(contentDir);

const banner =
  '// AUTO-GENERATED by scripts/build-blog-content.mjs from content/blog/*.md — do not edit by hand.\n';

const body = `${banner}
export interface BlogPost {
  slug: string;
  title: string;
  dateISO: string;
  description: string;
  image: string | null;
  lang: 'en' | 'pt';
  contentHtml: string;
}

export const blogPosts: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body);
console.log(`✅ Generated ${posts.length} blog post(s) → ${path.relative(process.cwd(), outFile)}`);
